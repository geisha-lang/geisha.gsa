#!/usr/bin/env python3
"""Generate src/stdlib_bundle.gsa and src/guide_bundle.gsa from stdlib/ and AGENT_GUIDE.md."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STDLIB_DIR = ROOT / "stdlib"
STDLIB_OUT = ROOT / "src" / "stdlib_bundle.gsa"
GUIDE_MD = ROOT / "AGENT_GUIDE.md"
GUIDE_OUT = ROOT / "src" / "guide_bundle.gsa"

MODULES = [
    ("std.option", "std/option.gsa"),
    ("std.result", "std/result.gsa"),
    ("std.list", "std/list.gsa"),
    ("std.control", "std/control.gsa"),
    ("std.bits", "std/bits.gsa"),
    ("std.path", "std/path.gsa"),
    ("std.char", "std/char.gsa"),
    ("std.buf", "std/buf.gsa"),
    ("std.str", "std/str.gsa"),
    ("std.vec", "std/vec.gsa"),
    ("std.map", "std/map.gsa"),
    ("std.sync", "std/sync.gsa"),
    ("std.task", "std/task.gsa"),
    ("std.actor", "std/actor.gsa"),
    ("std.rand", "std/rand.gsa"),
    ("std.math", "std/math.gsa"),
    ("std.generic", "std/generic.gsa"),
    ("std.codec", "std/codec.gsa"),
    ("std.json", "std/json.gsa"),
    ("std.toml", "std/toml.gsa"),
    ("std.sha256", "std/sha256.gsa"),
    ("sys.io", "sys/io.gsa"),
    ("sys.fs", "sys/fs.gsa"),
    ("sys.env", "sys/env.gsa"),
    ("sys.proc", "sys/proc.gsa"),
    ("sys.time", "sys/time.gsa"),
    ("sys.net", "sys/net.gsa"),
    ("sys.ffi", "sys/ffi.gsa"),
]


def escape_gs_string(raw: str) -> str:
    out = []
    for ch in raw:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def render_stdlib_bundle() -> str:
    lines = [
        "// Auto-generated by scripts/gen_stdlib.py — embedded std.* and sys.* module sources",
        "",
        "use std.option.{Option, Some, None}",
        "",
        "pub def builtinModuleKeys(): List String = [",
    ]
    for mod_key, _ in MODULES:
        lines.append(f'    "{mod_key}",')
    lines.append("]")
    lines.append("")
    lines.append("pub def builtinModuleSource(key: String): Option String =")
    for idx, (mod_key, rel_path) in enumerate(MODULES):
        content = (STDLIB_DIR / rel_path).read_text(encoding="utf-8")
        escaped = escape_gs_string(content)
        prefix = "    if" if idx == 0 else "    else if"
        lines.append(f'{prefix} (key == "{mod_key}") Some("{escaped}")')
    lines.append("    else None")
    lines.append("")
    return "\n".join(lines)


def render_guide_bundle() -> str:
    content = GUIDE_MD.read_text(encoding="utf-8")
    escaped = escape_gs_string(content)
    lines = [
        "// Auto-generated by scripts/gen_stdlib.py from AGENT_GUIDE.md — do not edit by hand",
        "",
        f'pub def embeddedAgentGuide(): String = "{escaped}"',
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    STDLIB_OUT.write_text(render_stdlib_bundle(), encoding="utf-8")
    if GUIDE_MD.exists():
        GUIDE_OUT.write_text(render_guide_bundle(), encoding="utf-8")


if __name__ == "__main__":
    main()
