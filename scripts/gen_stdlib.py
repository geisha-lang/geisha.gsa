#!/usr/bin/env python3
"""Generate src/stdlib_bundle.gs from stdlib/{std,sys}/*.gs."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STDLIB_DIR = ROOT / "stdlib"
OUT_FILE = ROOT / "src" / "stdlib_bundle.gs"

MODULES = [
    ("std.option", "std/option.gs"),
    ("std.result", "std/result.gs"),
    ("std.list", "std/list.gs"),
    ("std.bits", "std/bits.gs"),
    ("std.path", "std/path.gs"),
    ("std.char", "std/char.gs"),
    ("std.buf", "std/buf.gs"),
    ("std.str", "std/str.gs"),
    ("std.vec", "std/vec.gs"),
    ("std.map", "std/map.gs"),
    ("std.sync", "std/sync.gs"),
    ("std.task", "std/task.gs"),
    ("std.actor", "std/actor.gs"),
    ("sys.io", "sys/io.gs"),
    ("sys.fs", "sys/fs.gs"),
    ("sys.env", "sys/env.gs"),
    ("sys.proc", "sys/proc.gs"),
]


def escape_gs_string(raw: str) -> str:
    out = []
    for ch in raw:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    lines = [
        "// Auto-generated by scripts/gen_stdlib.py — embedded std.* and sys.* module sources",
        "",
        "use std.option.{Option, Some, None}",
        "",
        "pub def builtinModuleSource(key: String): Option String =",
    ]
    for idx, (mod_key, rel_path) in enumerate(MODULES):
        content = (STDLIB_DIR / rel_path).read_text(encoding="utf-8")
        escaped = escape_gs_string(content)
        prefix = "    if" if idx == 0 else "    else if"
        lines.append(f'{prefix} (key == "{mod_key}") Some("{escaped}")')
    lines.append("    else None")
    lines.append("")
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
